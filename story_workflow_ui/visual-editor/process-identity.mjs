import {execFile,execFileSync} from 'node:child_process';
import {promisify} from 'node:util';
import {readFile} from 'node:fs/promises';
import {readFileSync} from 'node:fs';
import {resolve} from 'node:path';
const run=promisify(execFile),pending=new Map();
let selfBirth;
export const validProcessBirth=birth=>typeof birth==='string'&&/^(?:windows:\d+|linux:[a-f0-9-]{36}:\d+)$/.test(birth);
const windowsProbe=pid=>({executable:resolve(process.env.SystemRoot??'C:/Windows','System32/WindowsPowerShell/v1.0/powershell.exe'),args:['-NoLogo','-NoProfile','-NonInteractive','-Command',`$candidate = [System.Diagnostics.Process]::GetProcessById(${pid}); $candidate.StartTime.ToUniversalTime().Ticks.ToString([System.Globalization.CultureInfo]::InvariantCulture)`],options:{windowsHide:true,timeout:10000,maxBuffer:4096}});
const windowsBirth=stdout=>{const ticks=stdout.trim();if(!/^\d+$/.test(ticks))throw Error('Invalid process start time');return 'windows:'+ticks;};
const linuxBirth=(stat,boot)=>{const ticks=stat.slice(stat.lastIndexOf(')')+2).trim().split(/\s+/)[19],birth='linux:'+boot.trim()+':'+ticks;if(!validProcessBirth(birth))throw Error('Invalid process start time');return birth;};
export function processAlive(pid){if(!Number.isSafeInteger(pid)||pid<=0)return false;try{process.kill(pid,0);return true;}catch(error){return error.code==='EPERM';}}
export function readProcessIdentitySync(pid){
 if(!processAlive(pid))return {state:'gone',pid};if(pid===process.pid&&selfBirth)return {state:'alive',pid,birth:selfBirth};
 try{
  let birth;
  if(process.platform==='win32'){const probe=windowsProbe(pid);birth=windowsBirth(execFileSync(probe.executable,probe.args,{...probe.options,encoding:'utf8',stdio:['ignore','pipe','pipe']}));}
  else if(process.platform==='linux')birth=linuxBirth(readFileSync(`/proc/${pid}/stat`,'utf8'),readFileSync('/proc/sys/kernel/random/boot_id','utf8'));
  else return {state:'unknown',pid};
  if(!processAlive(pid))return {state:'gone',pid};if(pid===process.pid)selfBirth=birth;return {state:'alive',pid,birth};
 }catch{return {state:processAlive(pid)?'unknown':'gone',pid};}
}
// A PID can be reused. Start identity is read from the OS, not a timestamp
// generated by the application. An unreadable identity is never proof of exit.
export function readProcessIdentity(pid){
 if(!processAlive(pid))return Promise.resolve({state:'gone',pid});
 if(pid===process.pid&&selfBirth)return Promise.resolve({state:'alive',pid,birth:selfBirth});
 if(pending.has(pid))return pending.get(pid);
 const operation=(async()=>{
  try{
   let birth;
   if(process.platform==='win32'){
    const probe=windowsProbe(pid),{stdout}=await run(probe.executable,probe.args,probe.options);birth=windowsBirth(stdout);
   }else if(process.platform==='linux'){
    const [stat,boot]=await Promise.all([readFile(`/proc/${pid}/stat`,'utf8'),readFile('/proc/sys/kernel/random/boot_id','utf8')]);
    birth=linuxBirth(stat,boot);
   }else return {state:'unknown',pid};
   if(!processAlive(pid))return {state:'gone',pid};if(pid===process.pid)selfBirth=birth;return {state:'alive',pid,birth};
  }catch{return {state:processAlive(pid)?'unknown':'gone',pid};}
 })();pending.set(pid,operation);operation.finally(()=>{if(pending.get(pid)===operation)pending.delete(pid);});return operation;
}
export async function recordedWorkerState(job,record,inspectProcess=readProcessIdentity){
 if(record?.token===job.workerToken&&(!job.workerPid||record.pid===job.workerPid)){
  if(!validProcessBirth(record.birth))return processAlive(record.pid)?'unknown':'gone';
  const current=await inspectProcess(record.pid);if(current.state==='gone')return 'gone';
  if(current.state==='alive'&&typeof current.birth==='string')return current.birth===record.birth?'alive':'gone';
  return 'unknown';
 }
 return processAlive(job.workerPid)?'unknown':'gone';
}
